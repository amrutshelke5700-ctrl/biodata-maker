export function getMarriageTitlePresets(language: AppLanguage): string[] {
  return RELIGION_CONFIGS.map((cfg) => cfg.defaultTitle[language]);
}

export function getReligionConfig(religion: ReligionType | undefined): ReligionConfig {
  return RELIGION_CONFIGS.find((item) => item.id === religion) || RELIGION_CONFIGS[0];
}

export function isKnownReligionDefaultTitle(title: string): boolean {
  const trimmed = title.trim();
  return RELIGION_CONFIGS.some((cfg) =>
    Object.values(cfg.defaultTitle).some((val) => val === trimmed)
  );
}

export function translateReligionSect(
  religion: ReligionType,
  rawSect: string,
  targetLanguage: AppLanguage
): string {
  const cfg = getReligionConfig(religion);
  const trimmed = rawSect.trim();
  if (!cfg.sectOptions || !trimmed) return rawSect;
  const lower = trimmed.toLowerCase();
  const match = cfg.sectOptions.find((opt) =>
    Object.values(opt.labels).some((lbl) => lbl.toLowerCase() === lower)
  );
  return match ? match.labels[targetLanguage] : rawSect;
}

export function resolveSectValue(
  religion: ReligionType,
  rawSect: string,
  language: AppLanguage
): string {
  const cfg = getReligionConfig(religion);
  const trimmed = rawSect.trim();
  if (!cfg.sectOptions || !trimmed) return '';
  const lower = trimmed.toLowerCase();
  const match = cfg.sectOptions.find((opt) =>
    Object.values(opt.labels).some((lbl) => lbl.toLowerCase() === lower)
  );
  return match ? match.labels[language] : '';
}

export function getReligionFieldValues(
  data: MarriageBiodata,
  language: AppLanguage
): Array<{ key: ReligionFieldKey; label: string; value: string }> {
  const cfg = getReligionConfig(data.religion);
  if (cfg.id === 'secular') return [];
  return cfg.fields.map((field) => ({
    key: field.key,
    label: field.label[language],
    value: data[field.key] || '',
  }));
}
